function visit(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) {
    if (["SCRIPT", "STYLE", "OPTION"].includes(n.parentElement?.tagName))
      continue;
    let record = records.get(n);
    if (!record || n.nodeValue !== record.last)
      record = { source: n.nodeValue, last: n.nodeValue };
    const next = translate(record.source);
    record.last = next;
    records.set(n, record);
    if (n.nodeValue !== next) n.nodeValue = next;
  }
}
